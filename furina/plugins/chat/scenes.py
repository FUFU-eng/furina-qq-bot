_recent: dict[str, deque] = {}


def _score(sc: dict, text: str) -> int:
    return sum(1 for t in sc["tags"] if t and t in text)


def pick(group_key, texts: list[str], reason: str = "", k: int = 2) -> list[dict]:
    """按最近几条消息挑场景：后面的消息权重更高；同群最近用过的先跳过。"""
    used = _recent.setdefault(str(group_key), deque(maxlen=6))
    texts = [str(t or "") for t in texts if t][-6:]
    scored = []
    for sc in SCENES:
        s = 0
        for i, t in enumerate(reversed(texts)):
            hit = _score(sc, t)
            if hit:
                s += hit * (3 if i == 0 else 1)
        if s:
            scored.append((s, random.random(), sc))
    scored.sort(key=lambda x: (-x[0], x[1]))
    out = [sc for _, _, sc in scored if sc["id"] not in used][:k]
    if not out and scored:
        out = [scored[0][2]]
    if not out and reason in ("idle", "random", "follow"):
        pool = [g for g in _GENERAL if g["id"] not in used] or _GENERAL
        if random.random() < 0.6:
            out = [random.choice(pool)]
    for sc in out:
        used.append(sc["id"])
    return out


def render(scenes: list[dict]) -> str:
    if not scenes:
        return ""
    rows = []
    for sc in scenes:
        turns = " / ".join(sc.get("turns") or [])
        prefer = " / ".join(f"「{p}」" for p in sc.get("prefer") or [])
        rows.append(f"- {sc['scene']}（比如：{turns}）→ 真人大概回 {prefer}；要点：{sc['learn']}")
    return ("【这种场合真人一般怎么回（只学长短和分寸，用你自己的口吻说，别照抄原句）】\n" + "\n".join(rows))


def note(group_key, texts: list[str], reason: str = "") -> str:
    try:
        return render(pick(group_key, texts, reason))
    except Exception:  # noqa: BLE001  示例只是锦上添花，出错就不带
        return ""

