def generic_daily_rules(name: str) -> str:
    """给非芙宁娜角色用的 DAILY_RULES：结构和指令标记完全一样，只去掉芙宁娜专属内容。"""
    out = []
    for line in DAILY_RULES.split("\n"):
        for prefix, repl in _GENERIC_LINE_SWAPS:
            if line.startswith(prefix):
                line = repl
                break
        out.append(line)
    text = "\n".join(out)
    return text.replace("芙芙", name or "我")


