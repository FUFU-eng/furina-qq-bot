"""去 AI 味：聊天回复发出去之前最后过一遍。

- 软毛病（客服式结尾、「总的来说」这类书面连接词）→ 直接删掉，不花 token；
- 硬毛病（自称 AI / 语言模型、「我理解你的感受」「这是个好问题」、markdown 标题加粗……）→ 让模型重说一次。
数字列表不算毛病：介绍功能时本来就要列。开关：AI_CHAT_DEAI（默认开）。
"""
from __future__ import annotations

import re

SOFT = [
    re.compile(r"[，,。！!\s]*(?:希望(?:这|以上)?(?:些|个)?(?:回答|内容|信息)?(?:能|可以)?对你有(?:所)?帮助)[^。！!\n]*[。！!～~]*"),
    re.compile(r"[，,。！!\s]*(?:如果你?(?:还)?有(?:其他|任何|别的)(?:问题|疑问|需要))[^。！!\n]*[。！!～~]*"),
    re.compile(r"[，,。！!\s]*(?:有(?:任何|什么)?(?:问题|需要)(?:的话)?)?随时(?:告诉|找|问|联系)我[^。！!\n]*[。！!～~]*"),
    re.compile(r"[，,。！!\s]*(?:欢迎随时|随时欢迎)[^。！!\n]*[。！!～~]*$"),
]
# 套路句式（数据来自 dsh-fish-tone 对 10 万条 B 站评论的统计：AI 是真人的 9~41 倍）。
# 一处两处真人也说；同一轮里换着用两种以上，才是 AI 味的指纹。
STRUCTURES = [
    ("不是…而是…", re.compile(r"不是[^。！？!?\n]{1,20}[，,]?\s*而是")),
    ("最…的是", re.compile(r"最[^。！？!?\n，,]{1,8}的是")),
    ("先…再…", re.compile(r"先[^。！？!?\n]{1,12}[，,]?\s*再")),
    ("不仅…更…", re.compile(r"不仅[^。！？!?\n]{1,20}(?:更|还|也)")),
    ("三段并列", re.compile(r"[^、，,\s]{1,8}、[^、，,\s]{1,8}(?:、|和|与|以及)[^、，,\s]{1,8}")),
]
DASH = re.compile(r"\s*—{2,}\s*")

CONNECTORS = re.compile(r"(?:^|(?<=[。！？!?\n，,]))\s*(?:总的来说|总而言之|综上所述|值得一提的是|需要注意的是|不得不说的是)[，,：:]?\s*")

HARD = re.compile(
    r"作为(?:一个|一名)?(?:AI|人工智能|语言模型|大模型|助手|聊天机器人)|我(?:只是|是)一个?(?:AI|人工智能|语言模型|程序)"
    r"|我(?:无法|不能)(?:提供|帮你|为你)|抱歉，?我(?:不能|无法)|我理解你的(?:感受|心情)|这是一个(?:很|非常)?好的?问题"
    r"|让我们一起|深入探讨|在这个.{1,12}的时代|^#{1,4}\s|\n#{1,4}\s|\*\*[^*\n]{1,40}\*\*"
    # 小鲸鱼作者 / QQ-agent 的 AI 腔黑名单：客服式陪伴、心理咨询腔、「记账上」这类被读者点名嫌弃的口头禅
    r"|(?:这笔|这个)?账(?:我)?(?:先)?(?:给你)?记(?:下了|上了|着了)|记(?:在)?账上"
    r"|我(?:会)?一直(?:都)?在(?:这里|这儿)?(?:陪着你)?(?:的)?[。！!～~]?$|我会一直陪着你|随时都在"
    r"|听起来(?:你|像是|好像)|我(?:能|可以|完全)理解(?:你|这种)|你的感受(?:很)?(?:重要|正常)"
    r"|有什么(?:我)?(?:可以|能)帮(?:你|到你)|需要我(?:帮你|为你)|还有什么(?:想|要)(?:聊|问|说)的吗"
)

RETRY_HINT = ("你刚才那句太像 AI 助手了（{why}）。你是群里的芙宁娜，不是助手：用平时聊天的口气重说同一个意思，"
              "短一点、口语一点，不要自称 AI，不要用 markdown 加粗或标题，不要客套。")


def soft_clean(text: str) -> str:
    if not text:
        return text
    out = text
    for p in SOFT:
        out = p.sub("", out)
    out = CONNECTORS.sub("", out)
    out = DASH.sub("，", out).strip("，")  # 聊天里没人打破折号
    out = re.sub(r"\n{3,}", "\n\n", out).strip()
    return out if len(out) >= 2 else text  # 删光了就别删


def hard_problem(text: str) -> str:
    """有硬毛病时返回命中的片段（给重试提示用），没有返回空串。"""
    m = HARD.search(text or "")
    return m.group(0).strip()[:20] if m else ""


def structure_problem(text: str) -> str:
    """同一轮里套路句式扎堆（≥2 种不同的）：返回命中的句式名，给重说提示用。"""
    kinds = [name for name, rx in STRUCTURES if rx.search(text or "")]
    return "套路句式扎堆：" + "、".join(kinds) if len(kinds) >= 2 else ""


def strip_markdown(text: str) -> str:
    """重试后还带 markdown 的兜底：去掉加粗和标题井号。"""
    t = re.sub(r"\*\*([^*\n]{1,40})\*\*", r"\1", text or "")
    return re.sub(r"(^|\n)#{1,4}\s*", r"\1", t)
